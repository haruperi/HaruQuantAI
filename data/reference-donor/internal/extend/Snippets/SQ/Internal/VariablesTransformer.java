	/**
	 * Find items.
	 *
	 * @param ruleElem the rule elem
	 * @return the array list
	 */
	private ArrayList<Element> findItems(Element ruleElem){
		ArrayList<Element> items = new ArrayList<>();

		ArrayList<Element> nestedElems = XMLUtil.getNestedElements(ruleElem, "Item");

		for(int i=0; i<nestedElems.size(); i++){
			Element itemElem = nestedElems.get(i);

			if(itemValid(itemElem)){	//block items don't have identification attribute
				items.add(itemElem);
			}
		}

		return items;
	}

