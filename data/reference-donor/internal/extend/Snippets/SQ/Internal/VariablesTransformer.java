	/**
	 * Item valid.
	 *
	 * @param itemElem the item elem
	 * @return true, if successful
	 */
	private boolean itemValid(Element itemElem){
		String key = itemElem.getAttributeValue("key");
		return key != null && !key.equals("AND") && !key.equals("OR");
	}

