	/**
	 * Find same string.
	 *
	 * @param s1 the s 1
	 * @param s2 the s 2
	 * @return the string
	 */
	private String findSameString(String s1, String s2) {
		StringBuilder sb1 = new StringBuilder();

		char c;
		for(int i=0; i<Math.min(s1.length(),s2.length()); i++){
			if((c = s1.charAt(i)) == s2.charAt(i)){
				sb1.append(c);
			}
		}
		return sb1.toString();
	}

