	/**
	 * speciality for periods and entry levels - verifies if the period is not used in indicator in entry order.
	 * If yes, it checks, if Entry (levels) is selected.
	 * @param paramElem
	 * @param parameterTypes
	 * @return
	 */
	private boolean checkEntryLevels(Element paramElem, ValuesMap parameterTypes) {
		if(parameterTypes == null) {
			return true;
		}

		Element elCurrent = paramElem;
		boolean isEntry = false;

		while(true) {
			Element el = elCurrent.getParentElement();
			if(el == null) {
				break;
			}

			String key = el.getAttributeValue("key");
			if(key != null && (key.contains("EnterAt") ||key.contains("ReverseAt"))) {
				isEntry = true;
				break;
			}

			elCurrent = el;
		}

		if(!isEntry) {
			return true; // generate variable
		}

		if(parameterTypes.getBoolean(ParametrizationTypes.ParamTypeEntryLevel)) {
			return true;
		}

		return false;
	}

