	/**
	 * Checks if is used.
	 *
	 * @param paramElem the param elem
	 * @return true, if is used
	 */
	private boolean isUsed(Element paramElem) {
		String isFormula = paramElem.getAttributeValue("isFormula");
		if(isFormula != null && isFormula.equals("true")) {
			Element elFormula = paramElem.getChild("Formula");
			String key = elFormula.getAttributeValue("key");

			if(key.endsWith(".None")) {
				return false;
			} else {
				return true;
			}
		}

		// it is normal parameter
		String defaultValue = paramElem.getAttributeValue("defaultValue");
		if(defaultValue == null) {
			return true;
		}

		String value = paramElem.getValue();
		if(value == null) {
			return true;
		}

		if(defaultValue.equals(value)) {
			// if value = default value hen the parameter is considered to be not used
			return false;
		}

		return true;
	}

