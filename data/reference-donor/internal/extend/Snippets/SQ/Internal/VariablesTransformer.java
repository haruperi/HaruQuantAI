	/**
	 * Transform to variables.
	 *
	 * @param symmetry the symmetry
	 * @param parameterTypes the parameter types
	 * @throws Exception the exception
	 */
	public void transformToVariables(boolean symmetry, ValuesMap parameterTypes) throws Exception{
		if(isTransformed()) backToNumbers();

		boolean hasRecommended;

		if(parameterTypes == null){
			// we'l keep it null, it will mean all parameters
			//parameterTypes = allParams;

			hasRecommended = false;
		} else {

			if(recognizeEmpty(parameterTypes)) {
				return;
			}

			hasRecommended = parameterTypes.getBoolean(ParametrizationTypes.ParamTypeRecommended, false);
			if(hasRecommended) {
				symmetry = true;
			}
		}

		Element strategyXML = strategy.getStrategyXml();

		ArrayList<Element> ruleElems = XMLUtil.getNestedElements(strategyXML, "Rule");

		String paramType;

		// replace all param values with variables
		for(int i=0; i<ruleElems.size(); i++) {
			Element ruleElem = ruleElems.get(i);
			RuleType ruleType = getRuleType(ruleElem);

			ArrayList<Element> items = findItems(ruleElem);

			for(int j=0; j<items.size(); j++) {
				Element itemElem = items.get(j);
				String itemKey = itemElem.getAttributeValue("key");

				List<Element> children = itemElem.getChildren("Param");

				for(int k=0; k<children.size(); k++) {
					Element paramElem = children.get(k);

					String paramKey = getParamKey(paramElem, itemKey);
					if(paramKey == null) continue;

					String isVariable = paramElem.getAttributeValue("variable");
					if(isVariable != null && isVariable.equals("true")) {
						// it already is variable
						String varRef = paramElem.getTextTrim();
						Variable existingVar = strategy.variables().get(varRef);
						if(existingVar == null && strategy.variables().getById(varRef) == null) {
							if(paramKey.equals("#Shift#") || paramKey.equals("#Type#")) {
								String defaultValue = paramElem.getAttributeValue("defaultValue");
								if(defaultValue != null) {
									paramElem.setText(defaultValue);
								} else {
									paramElem.setText("0");
								}
								paramElem.setAttribute("variable", "false");
								// fall through to normal processing
							} else {
								fixMinMaxVariable(paramElem);
								continue;
							}
						} else {
							fixMinMaxVariable(paramElem);
							continue;
						}
					}

					if(paramElem.getChildren().size() > 0) {
						ArrayList<Element> nestedElems = XMLUtil.getNestedElements(paramElem, "Param");

						for(int l=0; l<nestedElems.size(); l++) {
							Element nestedParam = nestedElems.get(l);

							boolean isExitParam = false;

							String formulaParentKey = getFormulaParentKey(nestedParam);
							if(formulaParentKey == null) {
								isExitParam = true;
							} else {
								if(formulaParentKey.contains(".PctValue") || formulaParentKey.contains(".FixedValue") || formulaParentKey.contains(".ATRBasedValue")) {
									isExitParam = true;
								}
							}

							if(isExitParam) {
								String nestedParamKey = getParamKey(nestedParam, itemKey);
								if(nestedParamKey != null){

									if(nestedParamKey.equals("#Value#")) {
										Element elParent = nestedParam.getParentElement();
										if(elParent.getAttributeValue("key").contains("ATR")) {
											nestedParamKey = "Coef";
										} else {
											nestedParamKey = "";
										}
									}


									if(nestedParamKey.equals("#AtrPeriod#")) {
										paramType = ParametrizationTypes.ParamTypeOtherParam;
									}
									else {
										paramType = getParameterType(paramElem, ruleType, itemKey, paramKey, true, formulaParentKey, nestedParamKey);
									}

									//we first check if the param value isn't a XML predefined variable. There may be some missing attributes
									if(!tryFixVariableAttributes(nestedParam, paramType)) {
										//if not, we process it further
										if(paramTypeToTransform(paramType, parameterTypes, hasRecommended)) {
											addVariable(nestedParam, symmetry, ruleType, itemKey, paramKey + nestedParamKey, paramType);
										}
									}
								}

							} else if(formulaParentKey.equals("SQ.Formulas.Price.UseFormula")) {
								// entry price
								String nestedParamKey = getParamKey(nestedParam, itemKey);
								if(nestedParamKey != null){
									paramType = getParameterType(paramElem, ruleType, itemKey, paramKey, true, formulaParentKey, nestedParamKey);

									//we first check if the param value isn't a XML predefined variable. There may be some missing attributes
									if(!tryFixVariableAttributes(nestedParam, paramType)) {
										//if not, we process it further
										if(paramTypeToTransform(paramType, parameterTypes, hasRecommended)) {
											if(paramType != ParametrizationTypes.ParamTypePeriod || checkEntryLevels(paramElem, parameterTypes)) {
												addVariable(nestedParam, symmetry, ruleType, itemKey, paramKey + "EntryMult", paramType);
											}
										}
									}
								}
							}
						}
					}
					else {
						paramType = getParameterType(paramElem, ruleType, itemKey, paramKey, false, null, null);

						//we first check if the param value isn't a XML predefined variable. There may be some missing attributes
						if(!tryFixVariableAttributes(paramElem, paramType)) {
							//if not, we process it further
							if(paramTypeToTransform(paramType, parameterTypes, hasRecommended)) {
								if(paramType != ParametrizationTypes.ParamTypePeriod || checkEntryLevels(paramElem, parameterTypes)) {
									addVariable(paramElem, symmetry, ruleType, itemKey, paramKey, paramType);
								}
							}
						}
					}
				}
			}
		}

		//for(Variable var : strategy.variables()) {
		//	Log.info("VAR: "+var.getName()+" type: "+ var.getType());
		//}

		//Load Trading Options variables

		if(parameterTypes == null || parameterTypes.getBoolean(ParametrizationTypes.ParamTypeTradingOptions, false)) {
			try {
				List<TradingOption> tradingOptions = TradingOptionsList.getInstance().getAvailableClasses();
				HashMap<String, TradingOption> strategyTradingOptions = null;

				Element elTradingOptions = strategyXML.getChild("TradingOptions");

				try {
					if(elTradingOptions != null) {
						TradingOptions options = ProjectConfigHelper.getOptions(elTradingOptions);

						strategyTradingOptions = new HashMap<>();

						for(int a=0; a<options.size(); a++) {
							TradingOption option = options.get(a);
							strategyTradingOptions.put(option.getClass().getSimpleName(), option);
						}
					}
				}
				catch(Exception e) {
					Log.error("Cannot load strategy trading options", e);
				}

				for(int a=0; a<tradingOptions.size(); a++) {
					TradingOption option = tradingOptions.get(a);
					String optionClass = option.getClass().getSimpleName();

					if(optionClass.equals("SessionOption") || optionClass.equals("StoreChartData") || optionClass.equals("ComputeDailyStats")) continue;

					ArrayList<IPGParameter> optionParams = option.getParams();

					TradingOption strategyOption = null;

					if(strategyTradingOptions != null && strategyTradingOptions.containsKey(optionClass)) {
						strategyOption = strategyTradingOptions.get(optionClass);
					}

					for(int i=0; i<optionParams.size(); i++) {
						IPGParameter param = optionParams.get(i);
						String paramKey = param.getKey();
						String variableKey = optionClass + "." + paramKey;
						String variableName = param.getName();
						String variableDataType = "string";

						String paramValue = null;
						if(strategyOption != null) {
							try {
								paramValue = String.valueOf(strategyOption.getParameterValue(paramKey));
							} catch(Exception e) {
								Log.error("Cannot set variable '" + variableKey + "'", e);
							}
						}

						try {
							Field paramField = option.getClass().getField(paramKey);
							String paramClass = paramField.getType().getSimpleName();
							Editor editorAnnotation = paramField.getAnnotation(Editor.class);
							Parameter parameterAnnotation = paramField.getAnnotation(Parameter.class);

							if(editorAnnotation != null && editorAnnotation.type() == Editors.Time) {
								variableDataType = "time";
							}
							else if(paramClass.equals(Boolean.class.getSimpleName()) || paramClass.equals(boolean.class.getSimpleName())){
								variableDataType = "boolean";
							}
							else if(paramClass.equals(Integer.class.getSimpleName()) || paramClass.equals(int.class.getSimpleName())) {
								variableDataType = "int";
							}
							else if(paramClass.equals(Double.class.getSimpleName()) || paramClass.equals(double.class.getSimpleName())) {
								variableDataType = "double";
							}
							else if(paramClass.equals(String.class.getSimpleName())) {
								variableDataType = "string";
							}
							else {
								Log.error("Unexpected trading option param class '" + paramClass + "', param field '"+ paramField.getName()+"'.");
							}

							if(paramValue == null) {
								if(parameterAnnotation != null) {
									paramValue = parameterAnnotation.defaultValue();
								}
								else {
									paramValue = param.print();
								}
							}
						}
						catch(Exception e) {
							Log.error("Cannot load trading option variable " + variableKey, e);
						}

						Variable variable = new Variable(
								variableKey,
								variableName,
								variableDataType,
								paramValue,
								true,
								ParametrizationTypes.ParamTypeTradingOptions,
								false
						);
						strategy.variables().add(variable);
					}
				}
			}
			catch(Exception e) {
				Log.error("Cannot load trading options variables", e);
			}
		}

		generateVariablesXML();
	}

