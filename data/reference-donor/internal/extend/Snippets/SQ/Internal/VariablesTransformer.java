	/**
	 * Adds the variable.
	 *
	 * @param paramElem the param elem
	 * @param symmetry the symmetry
	 * @param ruleType the rule type
	 * @param itemKey the item key
	 * @param paramKey the param key
	 * @param paramType the param type
	 */
	private String addVariable(Element paramElem, boolean symmetry, RuleType ruleType, String itemKey, String paramKey, String paramType){
		String type = paramElem.getAttributeValue("type");
		if(type == null) {
			if(paramElem.getAttributeValue("key").equals("#Number#")) {
				type = "double";
			} else {
				return null;
			}
		}

		// toto prida HighestInRange.TimeFrom/To parameters, ale su typu string, nie time.
		// mli by sa aj v snippetoch prerobit na typ int, potom by mali fungovat
		//if(!paramKey.equals("#TimeFrom#") && !paramKey.equals("#TimeTo#")) {
		if(type.equals("data") || type.equals("string")) {
			// skip variables for chart
			return null;
		}
		//}

		if(paramKey.contains("Direction") || paramKey.equals("#MagicNumber#")) {
			// skip variables for these params
			return null;
		}

		paramKey = SQUtils.renameActionParams(paramKey);
		paramKey = paramKey.replace("#", "");

		paramElem.setAttribute("variable", "true");

		String value = paramElem.getTextTrim();

		if(strategy.variables().getById(value) != null) {
			//it's not a simple value, but already defined variable
			return null;
		}

		if(value.endsWith(".00")) {
			value = value.substring(0, value.length()-3);
		}

		if(value.contains(".")) {
			while(value.endsWith("0")) {
				value = value.substring(0, value.length()-1);
			}
		}

		if(value.endsWith(".")) {
			value = value.substring(0, value.length()-1);
		}

		String variableName = generateVariableName(paramElem, symmetry, ruleType, itemKey, paramKey, value);

		if(strategy.variables().get(variableName) == null){
			Variable variable = new Variable(
					variableName,
					variableName,
					type,
					value,
					true,
					paramType,
					false
			);
			strategy.variables().add(variable);

			paramElem.setText(variableName);
		}
		else {
			paramElem.setText(strategy.variables().get(variableName).getId());
		}

		return variableName;
	}

