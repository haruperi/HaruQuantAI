	/**
	 * Gets the formula parent key.
	 *
	 * @param el the el
	 * @return the formula parent key
	 */
	private String getFormulaParentKey(Element el) {

		for(int i=0; i<50; i++) {
			Element elParent = el.getParentElement();

			if(elParent == null) {
				return null;
			}

			if(elParent.getName().equals("Formula")) {
				return elParent.getAttributeValue("key");
			}

			el = elParent;
		}

		return null;
	}

