	/**
	 * Fix min max variable.
	 *
	 * @param paramElem the param elem
	 */
	private void fixMinMaxVariable(Element paramElem) {
		String variableId = paramElem.getText();
		if(variableId== null) {
			return;
		}

		Variable var = strategy.variables().getById(variableId);
		if(var == null) {
			return;
		}

		// try to set variable min and max using element parameters
		double min = Integer.MAX_VALUE;
		double max = -Integer.MAX_VALUE;

		String controlType = paramElem.getAttributeValue("controlType");
		if(controlType == null) {
			return;
		}

		if(controlType.contains("jspinner")) {
			// to do later

		}
		else if(controlType.contains("combo")) {
			String values = paramElem.getAttributeValue("values");
			if(values == null) {
				return;
			}

			String[] vals = values.split(",");
			if(vals == null || vals.length == 0)  {
				return;
			}

			for(int i=0; i<vals.length; i++) {
				String[] vals2 = vals[i].split("=");

				if(vals2 == null || vals2.length != 2) {
					continue;
				}

				double doubleVal = Double.parseDouble(vals2[1]);

				if(doubleVal < min) {
					min = doubleVal;
				}
				if(doubleVal > max) {
					max = doubleVal;
				}
			}
		}

		// nevim, proc nasledujici radek byl zakomentovan, musi tady byt
		if(min == Integer.MAX_VALUE && max == -Integer.MAX_VALUE) return;

		var.setMinMax(min, max);
	}

