	/**
	 * Recognize rule type from element.
	 *
	 * @param paramElem the param elem
	 * @param ruleType the rule type
	 * @return the rule type
	 */
	private RuleType recognizeRuleTypeFromElement(Element paramElem, RuleType ruleType) {
		Element elSignal = XMLUtil.findFirstParent(paramElem, "signal");
		if(elSignal == null) {
			return ruleType;
		}

		String varId = elSignal.getAttributeValue("variable");
		if(varId == null) {
			return ruleType;
		}

		switch(varId) {
			case StrategyStandardTemplateSQ4.SGN_LONG_ENTRY_ID: return RuleType.LONG;
			case StrategyStandardTemplateSQ4.SGN_LONG_EXIT_ID: return RuleType.LONG;
			case StrategyStandardTemplateSQ4.SGN_SHORT_ENTRY_ID: return RuleType.SHORT;
			case StrategyStandardTemplateSQ4.SGN_SHORT_EXIT_ID: return RuleType.SHORT;
		}

		return ruleType;
	}

