	/**
	 * Generate variable name.
	 *
	 * @param paramElem the param elem
	 * @param symmetry the symmetry
	 * @param ruleType the rule type
	 * @param itemKey the item key
	 * @param paramKey the param key
	 * @param value the value
	 * @return the string
	 */
	private String generateVariableName(Element paramElem, boolean symmetry, RuleType ruleType, String itemKey, String paramKey, String value) {
		if(ruleType.equals(RuleType.UNKNOWN)) {
			symmetry = true;
		}

		String name = "";
		String newItemKey = null;

		if(symmetry) {
			String oppositeItemKey = Blocks.getOppositeBlockKey(itemKey);
			if(!oppositeItemKey.equals(itemKey)) {
				// blocks have different names, for example DEMChangesUp / DEMChangesDown
				// remove the difference and create only DEMChanges
				newItemKey = findSameString(itemKey, oppositeItemKey);
			}

		} else {
			if(ruleType.equals(RuleType.TRADING_SIGNALS)) {
				ruleType = recognizeRuleTypeFromElement(paramElem, ruleType);
			}

			name = (ruleType.equals(RuleType.LONG) ? "Long" : "Short");
		}

		if(itemKey.contains("EnterAt")) {
			itemKey = "";
		}

		if(itemKey.equals(paramKey)) {
			name += (newItemKey != null ? newItemKey : itemKey);
		} else {
			name += (newItemKey != null ? newItemKey : itemKey) + paramKey;
		}

		String parts[] = paramKey.split("\\.");

		if(parts.length == 2) {
			if(parts[0].equals(parts[1])) {
				paramKey = parts[0];

			} else if(parts[1].contains(parts[0])) {
				paramKey = parts[1].replace(parts[0], "");
			}
		}

		int index = 1;
		String finalName = shortenName(name + index);

		Variable variable = strategy.variables().get(finalName);

		while(variable != null && !variable.getValue().equals(value)){
			index++;
			finalName = shortenName(name + index);
			variable = strategy.variables().get(finalName);
		}

		finalName = finalName.replace(".", "_");

		return finalName;
	}

