	/**
	 * Gets the parameter type.
	 *
	 * @param paramElem the param elem
	 * @param ruleType the rule type
	 * @param itemKey the item key
	 * @param paramKey the param key
	 * @param isNested the is nested
	 * @param formulaParentKey the formula parent key
	 * @param nestedParamKey the nested param key
	 * @return the parameter type
	 */
	private String getParameterType(Element paramElem, RuleType ruleType, String itemKey, String paramKey, boolean isNested, String formulaParentKey, String nestedParamKey) {
		if(paramKey.contains("#BarsValid#") || paramKey.contains("#ReplaceExisting#")) {
			return ParametrizationTypes.ParamTypeEntryLogic;
		}

		String paramType = paramElem.getAttributeValue("type");
		if(paramType != null && paramType.equals("boolean")){
			return ParametrizationTypes.ParamTypeBoolean;
		}

		if(paramKey.contains("Period#") || paramKey.startsWith("#Fast") || paramKey.startsWith("#Slow") || paramKey.startsWith("#Smooth") || paramKey.contains("#Period")) {
			return ParametrizationTypes.ParamTypePeriod;
		}

		if(paramKey.equals("#Shift#")) {
			return ParametrizationTypes.ParamTypeShift;
		}

		if(paramKey.equals("#Line#")) {
			return ParamTypeLine;
		}

		if(paramKey.equals("#Value#")) {
			String controlType = paramElem.getAttributeValue("controlType");
			if(controlType != null && controlType.equals("combo")) {
				return ParamTypeLine;
			}
		}

		String genMinValue = paramElem.getAttributeValue("genMinValue");
		if(genMinValue != null) {
			if(genMinValue.equals(minPeriod)) {
				return ParametrizationTypes.ParamTypePeriod;
			}

			if(genMinValue.equals(minShift)) {
				return ParametrizationTypes.ParamTypeShift;
			}
		}

		if(itemKey.equals("Number") || paramKey.equals("#Level#")) {
			return ParametrizationTypes.ParamTypeConstant;
		}

		if(!isNested) {
			if(itemKey.startsWith("EnterAt") || itemKey.startsWith("EnterReverseAt")) {
				if(paramKey.equals("#ExitAfterBars.ExitAfterBars#")) {
					String value = paramElem.getText();

					if(value.equals("0")) {
						return ParametrizationTypes.ParamTypeExitUnused;
					}
				}

				if(isUsed(paramElem)) {
					return ParametrizationTypes.ParamTypeExitUsed;
				} else {
					return ParametrizationTypes.ParamTypeExitUnused;
				}
			}

			if(paramType.equals("int")) {
				// it can still be a period param
				if(tryRecognizePeriodParam(itemKey, paramKey)) {
					return ParametrizationTypes.ParamTypePeriod;
				}
			}

			return ParametrizationTypes.ParamTypeOtherParam;
		}

		if(isNested) {
			// it must be parameter in Entry Order
			if(formulaParentKey != null && formulaParentKey.equals("SQ.Formulas.Price.UseFormula")) {
				// it is part of entry
				if(nestedParamKey != null && (nestedParamKey.equals("#Number#"))) {
					if(itemKey.equals("AssignVariable")) {
						return ParamTypeUnknown;
					}
					return ParametrizationTypes.ParamTypeEntryLevel;
				} else {
					return ParamTypeUnknown;
				}
			}
			if(isUsed(paramElem)) {
				return ParametrizationTypes.ParamTypeExitUsed;
			} else {
				return ParametrizationTypes.ParamTypeExitUnused;
			}

		}

		return ParamTypeUnknown;
	}

