	/**
	 * Generate variables XML.
	 *
	 * @throws Exception the exception
	 */
	private void generateVariablesXML() throws Exception{
		Element variablesElem = getChildElem(getChildElem(strategy.getStrategyXml(), "Strategy"), "Variables");

		variablesElem.removeContent();
		Variables vars = strategy.variables();

		for(int i=0; i<vars.size(); i++) {
			Variable variable = vars.get(i);

			Element variableElem = variable.getXML().detach();

			if(variable.isAutoGenerated()){
				variableElem.setAttribute(generatedAttrName, "true");
			}

			if(variable.isMakeExternal()) {
				variableElem.setAttribute(makeExternalAttrName, "true");
			}

			variablesElem.addContent(variableElem);
		}
	}

