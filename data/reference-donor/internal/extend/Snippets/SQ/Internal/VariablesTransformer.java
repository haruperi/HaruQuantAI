	private boolean IsSignalVariable(String name){
		Variable existingVariable = strategy.variables().get(name);
		if(existingVariable != null){
			ArrayList<Element> signalElems = XMLUtil.getNestedElements(strategy.getStrategyXml(), "signal");
			for(int i=0; i<signalElems.size(); i++) {
				Element signalElem = signalElems.get(i);
				if(signalElem.getAttributeValue("variable").equals(existingVariable.getId())){
					return true;
				}
			}
		}
		return false;
	}
	/**
	 * Try fix variable attributes.
	 *
	 * @param paramElem the param elem
	 * @param paramType the param type
	 * @return true, if successful
	 */
	private boolean tryFixVariableAttributes(Element paramElem, String paramType){
		String value = paramElem.getText();
		String type = paramElem.getAttributeValue("type");

		if(value != null) {
			if(paramElem.getAttributeValue("variable") == null) {
				Variable existingVariable = strategy.variables().get(value);
				if (existingVariable != null) {
					if (!IsSignalVariable(value)) {
						// If signal variable marked as variable (true), the monte carlo tests wouldn't run
						paramElem.setAttribute("variable", "true");
					}

					if (type != null) {
						paramElem.setAttribute("variableType", type.toUpperCase());
					}
					existingVariable.setParamType(paramType);
					return true;
				}
			} else {
				// it already is variable. Check if it exists
				Variable existingVariable = strategy.variables().get(value);
				if (existingVariable != null) {
					return true; // don't create new variable
				}
			}
		}

		return false;
	}

