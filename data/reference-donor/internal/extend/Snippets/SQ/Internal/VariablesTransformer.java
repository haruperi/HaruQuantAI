	private boolean tryRecognizePeriodParam(String itemKey, String paramKey) {
		try {
			IBlock block = Blocks.get(itemKey);
			Class<?> aClass = block.getClass();

			paramKey = paramKey.replace("#", "");

			Field[] fields = aClass.getFields();
			for(int i=0; i<fields.length; i++) {
				Field field = fields[i];

				if(field.getName().equals(paramKey)) {
					for(Annotation annotation : field.getAnnotations()) {
						if(annotation instanceof Parameter) {
							if(((Parameter) annotation).isPeriod()) {
								return true;
							}
						}
					}
				}
			}

		} catch(Exception e) {
			if(e.getMessage().contains("talib_")) {
				Log.debug("Error recognizing parameter type from class: " + e.getMessage());
			} else {
				Log.error("Error recognizing parameter type from class: " + e.getMessage());
			}
		}

		return false;
	}

