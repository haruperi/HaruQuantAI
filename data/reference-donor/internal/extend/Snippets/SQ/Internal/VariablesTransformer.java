	/**
	 * Param type to transform.
	 *
	 * @param paramType the param type
	 * @param parameterTypes the parameter types
	 * @param hasRecommended the has recommended
	 * @return true, if successful
	 */
	private boolean paramTypeToTransform(String paramType, ValuesMap parameterTypes, boolean hasRecommended) {
		if(paramType == null) {
			return false;
		}

		if(hasRecommended) {
			if(paramType.equals(ParametrizationTypes.ParamTypePeriod) || paramType.equals(ParametrizationTypes.ParamTypeEntryLevel) || paramType.equals(ParametrizationTypes.ParamTypeExitUsed)) {
				return true;
			}
		}

		if(parameterTypes == null) {
			return true;
		}

		return parameterTypes.getBoolean(paramType, false);
	}

