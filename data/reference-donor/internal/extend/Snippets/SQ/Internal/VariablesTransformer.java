	/**
	 * Param not allowed.
	 *
	 * @param paramKey the param key
	 * @param itemKey the item key
	 * @return true, if successful
	 */
	private boolean paramNotAllowed(String paramKey, String itemKey){
		return paramKey.equals("#MagicNumber#") ||
				paramKey.equals("#ComputedFrom#") ||
				(itemKey.startsWith("EnterAt") && paramKey.equals("#Direction#")) ||
				(itemKey.startsWith("EnterAt") && paramKey.equals("#Size#"));
	}

