	/**
	 * Gets the param key.
	 *
	 * @param paramElem the param elem
	 * @param itemKey the item key
	 * @return the param key
	 */
	private String getParamKey(Element paramElem, String itemKey){
		String paramKey = paramElem.getAttributeValue("key");
		String type = paramElem.getAttributeValue("type");

		if(paramKey == null) {
			Log.error("Parameter of item '" + itemKey + "' doesn't have key attribute");

		} else if(paramNotAllowed(paramKey, itemKey)){
			//Magic numbers ignored

		} else if(type == null){

			if(paramKey.equals("#Number#")) {
				return paramKey;
			}

			Log.error("Parameter '{}' doesn't have type attribute", paramKey);

		} else if(type.equals("unknown")){
			//unknown types ignored
		}
		else {
			return paramKey;
		}

		return null;
	}

