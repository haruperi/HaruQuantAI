	/**
	 * Gets the rule type.
	 *
	 * @param ruleElem the rule elem
	 * @return the rule type
	 * @throws Exception the exception
	 */
	private RuleType getRuleType(Element ruleElem) throws Exception{
		String name = ruleElem.getAttributeValue("name");
		if(name == null){
			throw new Exception("Rule doesn't have a name");
		}

		if(name.startsWith("Long")) return RuleType.LONG;
		else if(name.startsWith("Short")) return RuleType.SHORT;
		else if(name.startsWith("Trading signals")) return RuleType.TRADING_SIGNALS;
		else if(name.startsWith("Explore")) return RuleType.EXPLORE;
		else return RuleType.UNKNOWN;
	}

