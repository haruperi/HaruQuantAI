	/**
	 * Removes the generated variables.
	 *
	 * @throws Exception the exception
	 */
	private void removeGeneratedVariables() throws Exception{
		Element variablesElem = getChildElem(getChildElem(strategy.getStrategyXml(), "Strategy"), "Variables");
		Iterator<Element> iterator = variablesElem.getChildren("variable").iterator();

		while(iterator.hasNext()) {
			Element variableElem = iterator.next();
			if(XMLUtil.elementIs(variableElem, generatedAttrName) && XMLUtil.elementIsNot(variableElem, makeExternalAttrName)){
				iterator.remove();
			}
		}

		Iterator<Variable> varIterator = strategy.variables().iterator();
		while(varIterator.hasNext()){
			Variable variable = varIterator.next();
			Element elVariable = variable.getXML();

			if(XMLUtil.elementIs(elVariable, generatedAttrName) && XMLUtil.elementIsNot(elVariable, makeExternalAttrName)){
				if(variable.isAutoGenerated()) {
					varIterator.remove();
				}
			}
		}

	}

