	/**
	 * Replace variable with number.
	 *
	 * @param paramElem the param elem
	 */
	private void replaceVariableWithNumber(Element paramElem){
		String variable = paramElem.getTextTrim();

		if(strategy.variables().get(variable) != null) {
			Variable var = strategy.variables().get(variable);
			if (var != null) {
				if (var.isAutoGenerated()) { // bug https://roadmap.strategyquant.com/tasks/sq4_011225
					// we should convert vars to numbers only for autogenerated variables!
					paramElem.setText(strategy.variables().get(variable).getValue());
					paramElem.setAttribute("variable", "false");
				} else {
					Element elVariable = var.getXML();
					if(elVariable != null && XMLUtil.elementIs(elVariable, generatedAttrName)) {
						paramElem.setText(var.getValue());
						paramElem.setAttribute("variable", "false");
					}
				}
			} else {
				//Log.error("Cannot find variable '" + variable + "'");
			}
		}
	}

