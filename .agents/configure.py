#!/usr/bin/env python3
"""Interactive runtime-policy generator for HaruQuantAI orchestration."""

from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

from runtime_policy import HEADLESS_MODES, RUNTIME_SCHEMA_VERSION

AGENTS_DIR = Path(__file__).resolve().parent
RUN_CONFIG = AGENTS_DIR / "run-config.toml"
ROLES = ("planner", "executor", "reviewer")
MODES = (
    (
        "solo",
        "Current IDE chat performs every role sequentially; Goals use one chat per child",
    ),
    ("solo-headless", "One shared native CLI conversation performs every role"),
    ("delegate", "Current IDE chat controls inspectable app-native role agents"),
    ("delegate-headless", "One CLI vendor with a dedicated conversation per role"),
    ("delegate-multi", "Independently configured CLI conversation per role"),
    ("manual", "Prepare validated artifacts for operator-managed role chats"),
)
VENDORS = ("zai", "codex", "agy", "cline")
MODELS: dict[str, tuple[str, ...]] = {
    "zai": ("glm-5.3", "glm-5.2"),
    "codex": ("gpt-5.6-sol", "gpt-5.6-terra", "gpt-5.6-luna"),
    "agy": ("gemini-3.7-flash-high", "gemini-3.6-flash-high"),
    "cline": ("glm-5.3", "glm-5.2"),
}
EFFORTS = ("low", "medium", "high", "xhigh", "max")


def _ask(prompt: str) -> str:
    try:
        return input(prompt).strip()
    except EOFError:
        sys.exit("No interactive input available.")


def _pick(label: str, options: tuple[str, ...], *, custom: bool = False) -> str:
    print(f"\n{label}")
    for index, option in enumerate(options, start=1):
        print(f"  {index}) {option}")
    while True:
        answer = _ask("Selection: ")
        if answer.isdigit() and 1 <= int(answer) <= len(options):
            return options[int(answer) - 1]
        if custom and answer:
            return answer
        print("Invalid selection.")


def _yes_no(label: str, *, default: bool = False) -> bool:
    suffix = "[Y/n]" if default else "[y/N]"
    while True:
        answer = _ask(f"{label} {suffix}: ").lower()
        if not answer:
            return default
        if answer in {"y", "yes"}:
            return True
        if answer in {"n", "no"}:
            return False
        print("Enter yes or no.")


def _role_spec(vendor: str, role_label: str) -> dict[str, str]:
    """Collect one visibly role-scoped headless transport identity."""
    prefix = f"[{role_label} / {vendor}]"
    model = _pick(f"{prefix} model", MODELS[vendor], custom=True)
    effort = _pick(f"{prefix} reasoning effort", EFFORTS, custom=True)
    provider = ""
    if vendor == "cline":
        provider = _ask(f"{prefix} Cline provider id: ")
        if not provider:
            raise ValueError("Cline requires a provider id.")
    if vendor == "zai":
        provider = "zai-coding-plan"
    return {
        "vendor": vendor,
        "model": model,
        "effort": effort,
        "provider": provider,
    }


def _role_lines(role: str, spec: dict[str, str]) -> list[str]:
    lines = [
        f"[roles.{role}]",
        f"vendor = {json.dumps(spec['vendor'])}",
        f"model = {json.dumps(spec['model'])}",
        f"effort = {json.dumps(spec['effort'])}",
    ]
    if spec["provider"]:
        lines.append(f"provider = {json.dumps(spec['provider'])}")
    return lines


def _render_config(
    *,
    mode: str,
    approval_policy: str,
    max_iterations: int,
    roles: dict[str, dict[str, str]],
    allow_execute: bool,
    allow_commit: bool,
    allow_merge: bool,
    recovery_enabled: bool,
) -> str:
    """Render one complete schema-v3 runtime policy."""
    lines = [
        "# Generated by .agents/configure.py; runtime-only and gitignored.",
        f"# generated: {dt.datetime.now(tz=dt.UTC).isoformat(timespec='seconds')}",
        f"schema_version = {RUNTIME_SCHEMA_VERSION}",
        f"mode = {json.dumps(mode)}",
        f"approval_policy = {json.dumps(approval_policy)}",
        f"max_iterations = {max_iterations}",
        "",
        "[unattended]",
        f"allow_execute = {str(allow_execute).lower()}",
        f"allow_local_commit = {str(allow_commit).lower()}",
        f"allow_local_merge = {str(allow_merge).lower()}",
        "",
        "[recovery]",
        f"enabled = {str(recovery_enabled).lower()}",
        f"max_escalations = {1 if recovery_enabled else 0}",
        f"additional_iterations = {1 if recovery_enabled else 0}",
        'vendor = "codex"',
        'model = "gpt-5.6-sol"',
        'effort = "high"',
    ]
    for role in ROLES:
        if role in roles:
            lines.extend(["", *_role_lines(role, roles[role])])
    return "\n".join(lines) + "\n"


def main() -> int:
    """Collect and persist one complete runtime policy."""
    print("HaruQuantAI agent workflow configuration")
    mode_display = _pick(
        "Orchestration mode",
        tuple(f"{name} — {description}" for name, description in MODES),
    )
    mode = mode_display.split(" — ", maxsplit=1)[0]
    approval_policy = _pick(
        "Approval policy",
        (
            "interactive — require exact owner messages at each gate",
            "unattended — use frozen run preauthorization",
        ),
    ).split(" — ", maxsplit=1)[0]
    maximum_text = _ask("Maximum normal iterations [5]: ") or "5"
    maximum = int(maximum_text)
    if maximum < 1:
        raise ValueError("Maximum iterations must be positive.")

    role_specs: dict[str, dict[str, str]] = {}
    if mode == "solo-headless":
        vendor = _pick("Vendor for the shared solo-headless session", VENDORS)
        shared = _role_spec(vendor, "shared solo")
        role_specs = {role: dict(shared) for role in ROLES}
    elif mode == "delegate-headless":
        vendor = _pick("Vendor for all roles", VENDORS)
        role_specs = {role: _role_spec(vendor, role) for role in ROLES}
    elif mode == "delegate-multi":
        role_specs = {
            role: _role_spec(_pick(f"[{role}] vendor", VENDORS), role) for role in ROLES
        }

    unattended = approval_policy == "unattended"
    allow_execute = unattended and _yes_no("Preauthorize plan execution?")
    allow_commit = unattended and _yes_no("Preauthorize local Task commit?")
    allow_merge = unattended and _yes_no("Preauthorize local no-ff merge?")
    recovery = False
    if unattended and mode in HEADLESS_MODES:
        recovery = _yes_no(
            "Enable one Sol/High recovery generation after max iterations?"
        )
    elif unattended:
        print(
            "Automatic Sol/High recovery sessions are headless-only; "
            "recovery remains disabled."
        )
    rendered = _render_config(
        mode=mode,
        approval_policy=approval_policy,
        max_iterations=maximum,
        roles=role_specs,
        allow_execute=allow_execute,
        allow_commit=allow_commit,
        allow_merge=allow_merge,
        recovery_enabled=recovery,
    )
    RUN_CONFIG.write_text(rendered, encoding="utf-8")
    print(f"[ok] wrote {RUN_CONFIG}")
    print("Tracked role TOMLs were not modified; run-config.toml is authoritative.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
