"""Shared strategy documents, market snapshots, and execution effects.

Description:
    Define typed host boundaries for legacy and canonical HSL strategies.
Purpose:
    FEAT-WIZARD-HSL-LANGUAGE: Consistent, explicit strategy execution boundaries.
Key Capabilities:
    - FR-shared-hsl-execution: Hosts log decisions; focused tests verify effects.
Python API Usage:
    Import the typed contracts and services from this module.
CLI Usage:
    uv run pytest tests/core/trading tests/workspace/algo_wizard --no-cov
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any

from app.core.data.contracts import MarketBar, MarketTick
from app.core.enums import OrderType, Timeframe
from app.core.trading.blocks.series import BarData
from app.core.trading.connection.contracts import OrderInfo, PositionInfo


class SignalConflictPolicy(StrEnum):
    """Resolution policy when contradictory signals trigger on same event."""

    FIRST_SIGNAL = "first_signal"
    CANCEL_BOTH = "cancel_both"
    REVERSE = "reverse"


class RuleTriggerKind(StrEnum):
    """Trigger conditions for rule execution."""

    ON_BAR_CLOSE = "on_bar_close"
    ON_BAR_OPEN = "on_bar_open"
    ON_TICK = "on_tick"
    ALL = "all"


class ActionKind(StrEnum):
    """Categorization of strategy rule action intents."""

    ENTER = "enter"
    EXIT = "exit"
    CANCEL = "cancel"
    MODIFY = "modify"


@dataclass(frozen=True, slots=True)
class BarUpdateEvent:
    """Historical or live bar update event."""

    symbol: str
    timeframe: Timeframe
    bar: MarketBar
    is_bar_close: bool = True


@dataclass(frozen=True, slots=True)
class TickUpdateEvent:
    """Intra-bar tick quote event."""

    symbol: str
    tick: MarketTick


@dataclass(frozen=True, slots=True)
class LifecycleEvent:
    """Explicit host lifecycle notification; time is UTC epoch seconds."""

    kind: str
    symbol: str
    time: int
    timeframe: str = ""
    payload: Mapping[str, Any] = field(default_factory=dict)


type EvaluationEvent = BarUpdateEvent | TickUpdateEvent | LifecycleEvent


@dataclass(frozen=True, slots=True)
class InstrumentEconomics:
    """Explicit account-currency valuation and executable quantity grid."""

    pip_size: float
    tick_size: float
    pip_value_per_lot: float
    contract_size: float
    min_volume: float
    max_volume: float
    volume_step: float


@dataclass(frozen=True, slots=True)
class OrderRequest:
    """Order creation request generated by strategy entry rules."""

    symbol: str
    direction: int  # 1 for Long/Buy, -1 for Short/Sell
    order_type: OrderType
    volume: float
    price: float = 0.0
    sl: float = 0.0
    tp: float = 0.0
    magic: int = 0
    comment: str = ""
    atm_rules: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class OrderModification:
    """Order modification request generated by strategy rules."""

    ticket: str | int
    price: float | None = None
    sl: float | None = None
    tp: float | None = None


@dataclass(frozen=True, slots=True)
class CloseRequest:
    """Position exit/close request generated by strategy exit rules."""

    ticket: str | int
    volume: float | None = None  # None indicates close entire position
    comment: str = ""


@dataclass(frozen=True, slots=True)
class StrategyEffects:
    """Immutable collection of trading effects emitted during strategy evaluation."""

    orders_to_open: tuple[OrderRequest, ...] = ()
    orders_to_cancel: tuple[str, ...] = ()
    orders_to_modify: tuple[OrderModification, ...] = ()
    positions_to_close: tuple[CloseRequest, ...] = ()
    state_updates: Mapping[str, Any] = field(default_factory=dict)
    alerts: tuple[Mapping[str, Any], ...] = ()


@dataclass(frozen=True, slots=True)
class ConditionDefinition:
    """Single condition evaluation specification."""

    left: str | float
    comparator: str = ">"
    right: str | float = 0.0
    composition_block_id: str | None = None
    composition_params: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class RuleAction:
    """Action intent emitted when rule conditions evaluate to True."""

    kind: ActionKind
    direction: int = 1
    order_type: OrderType = OrderType.BUY
    volume: float = 1.0
    price_offset: float = 0.0
    sl_pips: float = 0.0
    tp_pips: float = 0.0
    sl_price: float = 0.0
    tp_price: float = 0.0
    target_ticket: str | int | None = None
    atm_rules: Mapping[str, Any] = field(default_factory=dict)
    comment: str = ""


@dataclass(frozen=True, slots=True)
class RuleDefinition:
    """Named rule containing triggers, conditions, and actions."""

    rule_id: str
    name: str = ""
    trigger: RuleTriggerKind = RuleTriggerKind.ON_BAR_CLOSE
    conditions: tuple[ConditionDefinition, ...] = ()
    actions: tuple[RuleAction, ...] = ()
    is_enabled: bool = True


@dataclass(frozen=True, slots=True)
class VariableDefinition:
    """Strategy internal state variable specification."""

    name: str
    var_type: str = "float"
    default_value: Any = 0.0


@dataclass(frozen=True, slots=True)
class ParameterDefinition:
    """Strategy user-configurable parameter specification."""

    name: str
    param_type: str = "float"
    value: Any = 0.0


@dataclass(frozen=True, slots=True)
class TradingSetupConfig:
    """Configuration for execution parameters and conflict policies."""

    conflict_policy: SignalConflictPolicy = SignalConflictPolicy.FIRST_SIGNAL
    max_open_positions: int = 1
    magic_number: int = 1000
    pip_size: float = 0.0001
    default_slippage: float = 0.0


@dataclass(frozen=True, slots=True)
class StrategyContext:
    """Market context snapshot for strategy evaluation."""

    bars: BarData | None = None
    bars_by_symbol: Mapping[str, BarData] = field(default_factory=dict)
    positions: tuple[PositionInfo, ...] = ()
    orders: tuple[OrderInfo, ...] = ()
    account_balance: float = 0.0
    variables: Mapping[str, Any] = field(default_factory=dict)
    bars_by_context: Mapping[tuple[str, str], BarData] = field(default_factory=dict)
    bar_close_times: Mapping[tuple[str, str], tuple[int, ...]] = field(
        default_factory=dict
    )
    economics: Mapping[str, InstrumentEconomics] = field(default_factory=dict)
    account_equity: float | None = None
    state: Mapping[str, Any] = field(default_factory=dict)
    session_open: bool | None = None
    entries_today: int | None = None


@dataclass(frozen=True, slots=True)
class StrategyDocument:
    """Slotted frozen document model representing a complete strategy."""

    strategy_id: str
    rules: tuple[RuleDefinition, ...]
    variables: tuple[VariableDefinition, ...] = ()
    params: tuple[ParameterDefinition, ...] = ()
    trading_setup: TradingSetupConfig = field(default_factory=TradingSetupConfig)
    hsl_json: str | None = None
    block_fingerprints: Mapping[str, str] = field(default_factory=dict)


