"""Shared pure formatting helpers and descriptor contracts for wizard code export.

Description:
    Provides deterministic, side-effect-free formatting helpers and platform
    descriptor contracts operating on NormalizedStrategy nodes without
    evaluating arbitrary string formulas or untrusted code. Supports MQL4,
    MQL5, EasyLanguage, NinjaTrader, JForex, and Pseudocode code generation.

Purpose:
    FEAT-WIZARD-TEMPLATE-HELPERS: Shared formatting foundation for Phase 5.10
    (WO-WZ-TEMPLATE-COHORTS, Gate G10) multi-platform strategy code export.

Key Capabilities:
    - FR-wizard-template-identifier-sanitize: Sanitizes strategy, parameter, and
      variable names into safe ASCII/PascalCase identifiers with structured logging.
    - FR-wizard-template-descriptor-spec: Defines immutable PlatformDescriptorSpec
      metadata for target export engines and file extensions.
    - FR-wizard-template-deterministic-render: Renders Jinja2 and structured line
      templates from NormalizedStrategy without dynamic eval/exec.

Python API Usage:
    from app.core.wizard.template_helpers import (
        PlatformDescriptorSpec,
        sanitize_identifier,
    )

    ident = sanitize_identifier("My Strategy 1")

CLI Usage:
    uv run python -m pytest tests/workspace/algo_wizard --no-cov -q
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from jinja2 import Environment

from app.core.host.logging import get_logger
from app.core.lib.errors import DomainError
from app.core.wizard.transform import NormalizedParam, NormalizedStrategy, NormalizedVar

logger = get_logger(__name__)

_NON_IDENT_RE = re.compile(r"[^a-zA-Z0-9_]+")


@dataclass(frozen=True, slots=True)
class PlatformDescriptorSpec:
    """Metadata descriptor for a multi-platform strategy code export target."""

    platform_id: str
    label: str
    extension: str
    language: str
    supports_stop_loss: bool = True
    supports_take_profit: bool = True
    options: tuple[str, ...] = ()


def sanitize_identifier(raw_name: str, fallback: str = "unnamed_strategy") -> str:
    """Sanitize an arbitrary name into a valid identifier without leading digits."""
    cleaned = _NON_IDENT_RE.sub("_", raw_name).strip("_")
    if cleaned and cleaned[0].isdigit():
        cleaned = f"s_{cleaned}"
    result = cleaned or fallback
    logger.debug(
        "FR-wizard-template-identifier-sanitize: raw=%s sanitized=%s",
        raw_name,
        result,
    )
    return result


def format_class_identifier(raw_name: str, fallback: str = "GeneratedStrategy") -> str:
    """Format an identifier as a PascalCase class name for C#, Java, or Python."""
    sanitized = sanitize_identifier(raw_name, fallback=fallback)
    parts = [part for part in sanitized.split("_") if part]
    pascal = "".join(part[:1].upper() + part[1:] for part in parts)
    return pascal or fallback


def format_parameter_value(param: NormalizedParam) -> str:
    """Format a normalized parameter default value deterministically."""
    if param.type_name in ("bool", "boolean"):
        return "true" if bool(param.value) else "false"
    return str(param.value)


def format_variable_value(var: NormalizedVar) -> str:
    """Format a normalized variable initial value deterministically."""
    if var.type_name in ("bool", "boolean"):
        return "true" if bool(var.value) else "false"
    return str(var.value)


def render_jinja_template(template_source: str, strategy: NormalizedStrategy) -> str:
    """Render a Jinja2 template string deterministically for a NormalizedStrategy."""
    if strategy.hsl_json is not None:
        from app.core.wizard.transform import PYTHON_TEMPLATE

        if template_source != PYTHON_TEMPLATE:
            raise DomainError(
                code="HSL_EXPORT_UNSUPPORTED",
                message="Target has no qualified HSL mapping",
            )
    env = Environment(
        autoescape=False,  # noqa: S701
        trim_blocks=True,
        lstrip_blocks=True,
    )
    template = env.from_string(template_source)
    rendered = str(template.render(strategy=strategy))
    logger.info(
        "FR-wizard-template-deterministic-render: rendered template for strategy=%s",
        strategy.strategy_id,
    )
    return rendered if rendered.endswith("\n") else f"{rendered}\n"


def render_ninjatrader_source(strategy: NormalizedStrategy) -> str:
    """Render deterministic NinjaTrader 8 C# NinjaScript strategy source code."""
    if strategy.hsl_json is not None:
        raise DomainError(
            code="HSL_EXPORT_UNSUPPORTED", message="Target has no qualified HSL mapping"
        )

    class_name = format_class_identifier(strategy.class_name)
    lines: list[str] = [
        "// Generated by HaruQuantAI Strategy Transformer (NinjaTrader 8)",
        "using System;",
        "using NinjaTrader.Cbi;",
        "using NinjaTrader.NinjaScript;",
        "using NinjaTrader.NinjaScript.Strategies;",
        "",
        "namespace NinjaTrader.NinjaScript.Strategies",
        "{",
        f"    public class {class_name} : Strategy",
        "    {",
    ]
    lines.extend(
        f"        public {param.type_cs} {param.name} {{ get; set; }} = "
        f"{format_parameter_value(param)};"
        for param in strategy.parameters
    )
    lines.extend(
        f"        private {var.type_mql} {var.name} = {format_variable_value(var)};"
        for var in strategy.variables
    )
    lines.extend(
        [
            "",
            "        protected override void OnBarUpdate()",
            "        {",
            "            if (CurrentBar < 20) return;",
        ]
    )
    for rule in strategy.rules:
        if not rule.is_enabled:
            continue
        lines.append(f"            // Rule: {rule.name}")
        lines.append(f"            if ({rule.cond_expr_cs})")
        lines.append("            {")
        for act in rule.actions:
            if act.kind == "enter":
                method = "EnterLong" if act.direction == 1 else "EnterShort"
                lines.append(f'                {method}("{act.comment}");')
            elif act.kind == "exit":
                lines.append("                ExitLong();")
                lines.append("                ExitShort();")
        lines.append("            }")
    lines.extend(["        }", "    }", "}", ""])
    logger.info(
        "FR-wizard-template-deterministic-render: rendered ninjatrader strategy=%s",
        strategy.strategy_id,
    )
    return "\n".join(lines)


def render_jforex_source(strategy: NormalizedStrategy) -> str:
    """Render deterministic Dukascopy JForex Java IStrategy source code."""
    if strategy.hsl_json is not None:
        raise DomainError(
            code="HSL_EXPORT_UNSUPPORTED", message="Target has no qualified HSL mapping"
        )

    class_name = format_class_identifier(strategy.class_name)
    lines: list[str] = [
        "// Generated by HaruQuantAI Strategy Transformer (JForex)",
        "package com.haruquant.strategies;",
        "",
        "import com.dukascopy.api.*;",
        "",
        f"public class {class_name} implements IStrategy {{",
        "    private IEngine engine;",
        "    private IHistory history;",
    ]
    lines.extend(
        f'    @Configurable("{param.name}") '
        f"public {param.type_mql} {param.name} = {format_parameter_value(param)};"
        for param in strategy.parameters
    )
    lines.extend(
        f"    private {var.type_mql} {var.name} = {format_variable_value(var)};"
        for var in strategy.variables
    )
    lines.extend(
        [
            "",
            "    @Override",
            "    public void onStart(IContext context) throws JFException {",
            "        this.engine = context.getEngine();",
            "        this.history = context.getHistory();",
            "    }",
            "",
            "    @Override",
            (
                "    public void onBar(Instrument instrument, Period period, "
                "IBar askBar, IBar bidBar) throws JFException {"
            ),
            "        double open = bidBar.getOpen();",
            "        double high = bidBar.getHigh();",
            "        double low = bidBar.getLow();",
            "        double close = bidBar.getClose();",
            "        double volume = bidBar.getVolume();",
        ]
    )
    for rule in strategy.rules:
        if not rule.is_enabled:
            continue
        lines.append(f"        // Rule: {rule.name}")
        lines.append(f"        if ({rule.cond_expr_cs}) {{")
        for act in rule.actions:
            if act.kind == "enter":
                cmd = (
                    "IEngine.OrderCommand.BUY"
                    if act.direction == 1
                    else "IEngine.OrderCommand.SELL"
                )
                lines.append(
                    f'            engine.submitOrder("{rule.name}", '
                    f"instrument, {cmd}, {act.volume});"
                )
            elif act.kind == "exit":
                lines.append(
                    "            for (IOrder o : engine.getOrders(instrument)) "
                    "{ o.close(); }"
                )
        lines.append("        }")
    lines.extend(
        [
            "    }",
            "",
            "    @Override",
            (
                "    public void onTick(Instrument instrument, ITick tick) "
                "throws JFException {}"
            ),
            "    @Override",
            "    public void onMessage(IMessage message) throws JFException {}",
            "    @Override",
            "    public void onAccount(IAccount account) throws JFException {}",
            "    @Override",
            "    public void onStop() throws JFException {}",
            "}",
            "",
        ]
    )
    logger.info(
        "FR-wizard-template-deterministic-render: rendered jforex strategy=%s",
        strategy.strategy_id,
    )
    return "\n".join(lines)


def render_pseudocode_source(
    strategy: NormalizedStrategy,
    *,
    display_name: str | None = None,
    schema_version: str = "1.0.0",
    symbols: tuple[str, ...] = ("EURUSD",),
    primary_timeframe: str = "H1",
    additional_timeframes: tuple[str, ...] = (),
    description: str = "",
) -> str:
    """Render deterministic human-readable strategy pseudocode specification."""
    if strategy.hsl_json is not None:
        document = json.loads(strategy.hsl_json)
        return (
            "STRATEGY: "
            + str(document["strategy"]["name"])
            + "\nCANONICAL HSL DEFINITION:\n"
            + json.dumps(document, indent=2, sort_keys=True)
            + "\n"
        )
    header_name = display_name or strategy.name
    lines: list[str] = [
        "======================================================================",
        f"STRATEGY: {header_name} ({strategy.strategy_id})",
        "======================================================================",
        f"Schema Version : {schema_version}",
        f"Symbols        : {', '.join(symbols)}",
        f"Primary TF     : {primary_timeframe}",
    ]
    if additional_timeframes:
        lines.append(f"Additional TFs : {', '.join(additional_timeframes)}")
    if description:
        lines.append(f"Description    : {description}")
    lines.append("")
    lines.append("PARAMETERS:")
    if strategy.parameters:
        lines.extend(
            f"  - {p.name} ({p.type_name}) = {p.value}" for p in strategy.parameters
        )
    else:
        lines.append("  (none)")
    lines.append("")
    lines.append("RULES:")
    for idx, rule in enumerate(strategy.rules, start=1):
        status = "ENABLED" if rule.is_enabled else "DISABLED"
        lines.append(f"  Rule #{idx}: {rule.name} [{status}] (Event: {rule.trigger})")
        lines.append(f"    WHEN: {rule.cond_expr_py}")
        lines.append("    THEN:")
        for act in rule.actions:
            side = "LONG" if act.direction == 1 else "SHORT"
            lines.append(
                f"      * {act.kind.upper()} {side} "
                f"(volume={act.volume}, comment='{act.comment}')"
            )
    lines.append("")
    logger.info(
        "FR-wizard-template-deterministic-render: rendered pseudocode strategy=%s",
        strategy.strategy_id,
    )
    return "\n".join(lines)


