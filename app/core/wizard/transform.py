class StrategyTransformer:
    """Strategy rule AST transformation and multi-platform code generator."""

    def __init__(self) -> None:
        self._env = Environment(
            autoescape=False,  # noqa: S701
            trim_blocks=True,
            lstrip_blocks=True,
        )
        self._templates: dict[str, Template] = {
            "mql5": self._env.from_string(MQL5_TEMPLATE),
            "mql4": self._env.from_string(MQL4_TEMPLATE),
            "easylanguage": self._env.from_string(EASYLANGUAGE_TEMPLATE),
            "ctrader": self._env.from_string(CTRADER_TEMPLATE),
            "python": self._env.from_string(PYTHON_TEMPLATE),
        }

    def _normalize_name(self, name: str) -> str:
        """Sanitize names into safe identifiers."""
        clean = re.sub(r"[^a-zA-Z0-9_]", "_", name)
        if clean and clean[0].isdigit():
            clean = f"var_{clean}"
        return clean or "unnamed_strategy"

    def _map_param(self, name: str, param_type: str, value: Any) -> NormalizedParam:
        ptype = str(param_type).lower()
        val: int | float | bool
        if ptype in ("int", "integer"):
            type_mql = "int"
            type_cs = "int"
            type_py = "int"
            val = int(value)
        elif ptype in ("bool", "boolean"):
            type_mql = "bool"
            type_cs = "bool"
            type_py = "bool"
            val = bool(value)
        else:
            type_mql = "double"
            type_cs = "double"
            type_py = "float"
            val = float(value)

        return NormalizedParam(
            name=self._normalize_name(name),
            type_name=ptype,
            type_mql=type_mql,
            type_cs=type_cs,
            type_py=type_py,
            value=val,
        )

    def _map_var(self, name: str, var_type: str, value: Any) -> NormalizedVar:
        vtype = str(var_type).lower()
        val: int | float | bool
        if vtype in ("int", "integer"):
            type_mql = "int"
            type_py = "int"
            val = int(value)
        elif vtype in ("bool", "boolean"):
            type_mql = "bool"
            type_py = "bool"
            val = bool(value)
        else:
            type_mql = "double"
            type_py = "float"
            val = float(value)

        return NormalizedVar(
            name=self._normalize_name(name),
            type_name=vtype,
            type_mql=type_mql,
            type_py=type_py,
            value=val,
        )

    def _map_operand(
        self,
        val: str | float,
        platform: str,
        rule_name: str,
        *,
        side: str,
        known_symbols: set[str],
        errors: list[str],
    ) -> str:
        if isinstance(val, (int, float)):
            return str(val)
        raw_str = str(val).strip()
        try:
            float(raw_str)
            return raw_str
        except ValueError:
            pass

        s = raw_str.lower()
        if s in _MARKET_FIELDS:
            price_map = {
                "open": "open_price" if platform == "python" else "open",
                "open_price": "open_price" if platform == "python" else "open",
                "high": "high_price" if platform == "python" else "high",
                "high_price": "high_price" if platform == "python" else "high",
                "low": "low_price" if platform == "python" else "low",
                "low_price": "low_price" if platform == "python" else "low",
                "close": "close_price" if platform == "python" else "close",
                "close_price": "close_price" if platform == "python" else "close",
                "volume": "volume",
                "tick_volume": "volume",
            }
            return price_map.get(s, self._normalize_name(raw_str))

        norm_name = self._normalize_name(raw_str)
        if raw_str in known_symbols or norm_name in known_symbols:
            if platform == "python":
                return f"self.{norm_name}"
            return norm_name

        if platform == "python":
            errors.append(
                f"Unresolved operand reference '{raw_str}' for {side} operand in "
                f"rule '{rule_name}' (must be a declared parameter, variable, "
                f"or market field)"
            )
        return ""

    def _normalize_condition(
        self,
        cond: ConditionDefinition,
        rule_name: str,
        errors: list[str],
        known_symbols: set[str],
    ) -> NormalizedCondition | None:
        """Validate and normalize a single condition definition."""
        if cond.composition_block_id:
            errors.append(
                f"Unsupported indicator composition block "
                f"'{cond.composition_block_id}' in rule '{rule_name}' "
                f"(indicator composition blocks are not supported for code generation)"
            )
            return None

        comp = cond.comparator.strip()
        if comp not in _SUPPORTED_COMPARATORS:
            errors.append(
                f"Unsupported comparator '{comp}' in rule '{rule_name}'. "
                f"Supported comparators are: {sorted(_SUPPORTED_COMPARATORS)}"
            )
            return None

        comp_mql = comp
        comp_cs = comp
        comp_py = comp
        comp_el = _COMPARATOR_MAP_EL.get(comp, comp)

        left_mql = self._map_operand(
            cond.left,
            "mql",
            rule_name,
            side="left",
            known_symbols=known_symbols,
            errors=errors,
        )
        left_el = self._map_operand(
            cond.left,
            "el",
            rule_name,
            side="left",
            known_symbols=known_symbols,
            errors=errors,
        )
        left_cs = self._map_operand(
            cond.left,
            "cs",
            rule_name,
            side="left",
            known_symbols=known_symbols,
            errors=errors,
        )
        left_py = self._map_operand(
            cond.left,
            "python",
            rule_name,
            side="left",
            known_symbols=known_symbols,
            errors=errors,
        )

        right_mql = self._map_operand(
            cond.right,
            "mql",
            rule_name,
            side="right",
            known_symbols=known_symbols,
            errors=errors,
        )
        right_el = self._map_operand(
            cond.right,
            "el",
            rule_name,
            side="right",
            known_symbols=known_symbols,
            errors=errors,
        )
        right_cs = self._map_operand(
            cond.right,
            "cs",
            rule_name,
            side="right",
            known_symbols=known_symbols,
            errors=errors,
        )
        right_py = self._map_operand(
            cond.right,
            "python",
            rule_name,
            side="right",
            known_symbols=known_symbols,
            errors=errors,
        )

        if not left_py or not right_py:
            return None

        return NormalizedCondition(
            expr_mql=f"{left_mql} {comp_mql} {right_mql}",
            expr_el=f"{left_el} {comp_el} {right_el}",
            expr_cs=f"{left_cs} {comp_cs} {right_cs}",
            expr_py=f"{left_py} {comp_py} {right_py}",
        )

    def _normalize_action(
        self, action: RuleAction, rule_name: str, errors: list[str]
    ) -> NormalizedAction:
        """Normalize execution action parameters."""
        sl_pips = float(action.sl_pips)
        tp_pips = float(action.tp_pips)

        kind_str = (
            action.kind.value if hasattr(action.kind, "value") else str(action.kind)
        )
        if kind_str not in ("enter", "exit"):
            errors.append(f"Unsupported action kind '{kind_str}' in rule '{rule_name}'")
        elif kind_str == "enter" and action.direction not in (1, -1):
            errors.append(
                f"Invalid direction '{action.direction}' for enter action "
                f"in rule '{rule_name}' (expected 1 or -1)"
            )

        if action.direction == 1:
            sl_expr_mql5 = (
                f"_Point * {sl_pips} > 0 ? "
                f"SymbolInfoDouble(_Symbol, SYMBOL_ASK) - {sl_pips} * _Point : 0"
                if sl_pips > 0
                else "0"
            )
            tp_expr_mql5 = (
                f"_Point * {tp_pips} > 0 ? "
                f"SymbolInfoDouble(_Symbol, SYMBOL_ASK) + {tp_pips} * _Point : 0"
                if tp_pips > 0
                else "0"
            )
            sl_expr_mql4 = f"Ask - {sl_pips} * Point" if sl_pips > 0 else "0"
            tp_expr_mql4 = f"Ask + {tp_pips} * Point" if tp_pips > 0 else "0"
        else:
            sl_expr_mql5 = (
                f"_Point * {sl_pips} > 0 ? "
                f"SymbolInfoDouble(_Symbol, SYMBOL_BID) + {sl_pips} * _Point : 0"
                if sl_pips > 0
                else "0"
            )
            tp_expr_mql5 = (
                f"_Point * {tp_pips} > 0 ? "
                f"SymbolInfoDouble(_Symbol, SYMBOL_BID) - {tp_pips} * _Point : 0"
                if tp_pips > 0
                else "0"
            )
            sl_expr_mql4 = f"Bid + {sl_pips} * Point" if sl_pips > 0 else "0"
            tp_expr_mql4 = f"Bid - {tp_pips} * Point" if tp_pips > 0 else "0"

        return NormalizedAction(
            kind=kind_str,
            direction=int(action.direction),
            volume=float(action.volume),
            sl_pips=sl_pips,
            tp_pips=tp_pips,
            sl_expr_mql5=sl_expr_mql5,
            tp_expr_mql5=tp_expr_mql5,
            sl_expr_mql4=sl_expr_mql4,
            tp_expr_mql4=tp_expr_mql4,
            comment=str(action.comment or "HaruStrategy"),
        )

    def normalize(
        self, document: StrategyDocument
    ) -> tuple[NormalizedStrategy | None, tuple[str, ...]]:
        """Map strategy rules and setup into intermediate representation."""
        errors: list[str] = []
        known_symbols: set[str] = set()

        for p in document.params:
            if not p.name.isidentifier() or keyword.iskeyword(p.name):
                errors.append(f"Invalid or reserved parameter identifier: '{p.name}'")
            known_symbols.add(p.name)
            known_symbols.add(self._normalize_name(p.name))

        for v in document.variables:
            if not v.name.isidentifier() or keyword.iskeyword(v.name):
                errors.append(f"Invalid or reserved variable identifier: '{v.name}'")
            known_symbols.add(v.name)
            known_symbols.add(self._normalize_name(v.name))

        params = tuple(
            self._map_param(p.name, p.param_type, p.value) for p in document.params
        )
        vars_list = tuple(
            self._map_var(v.name, v.var_type, v.default_value)
            for v in document.variables
        )

        norm_rules: list[NormalizedRule] = []
        for rule in document.rules:
            r_name = rule.name or rule.rule_id
            norm_conds: list[NormalizedCondition] = []
            for cond in rule.conditions:
                nc = self._normalize_condition(cond, r_name, errors, known_symbols)
                if nc is not None:
                    norm_conds.append(nc)

            norm_acts = tuple(
                self._normalize_action(act, r_name, errors) for act in rule.actions
            )
            cond_mql = " && ".join(c.expr_mql for c in norm_conds)
            cond_el = " and ".join(c.expr_el for c in norm_conds)
            cond_cs = " && ".join(c.expr_cs for c in norm_conds)
            cond_py = " and ".join(c.expr_py for c in norm_conds)

            norm_rules.append(
                NormalizedRule(
                    name=self._normalize_name(r_name),
                    trigger=str(rule.trigger),
                    conditions=tuple(norm_conds),
                    actions=norm_acts,
                    is_enabled=rule.is_enabled,
                    cond_expr_mql=cond_mql,
                    cond_expr_el=cond_el,
                    cond_expr_cs=cond_cs,
                    cond_expr_py=cond_py,
                )
            )

        if errors:
            return None, tuple(errors)

        safe_name = self._normalize_name(document.strategy_id)
        class_name = "".join(
            part[:1].upper() + part[1:] for part in safe_name.split("_") if part
        )

        norm_strategy = NormalizedStrategy(
            strategy_id=document.strategy_id,
            name=safe_name,
            class_name=class_name or "GeneratedStrategy",
            magic_number=int(document.trading_setup.magic_number),
            max_positions=int(document.trading_setup.max_open_positions),
            parameters=params,
            variables=vars_list,
            rules=tuple(norm_rules),
        )
        return norm_strategy, ()

    def transform(
        self, document: StrategyDocument, target_platform: str
    ) -> ExportResult:
        """Render target platform source code using Jinja2 templates."""
        plat = target_platform.strip().lower()
        if plat not in SUPPORTED_PLATFORMS:
            err = (
                f"Unsupported platform: '{target_platform}'. "
                f"Supported platforms are: {', '.join(sorted(SUPPORTED_PLATFORMS))}"
            )
            return ExportResult(
                success=False, source_code="", errors=(err,), platform=target_platform
            )

        norm_strategy, errors = self.normalize(document)
        if errors or norm_strategy is None:
            return ExportResult(
                success=False, source_code="", errors=errors, platform=target_platform
            )

        template = self._templates[plat]
        try:
            rendered = template.render(strategy=norm_strategy)
        except Exception as exc:  # noqa: BLE001
            return ExportResult(
                success=False,
                source_code="",
                errors=(f"Template rendering failed: {exc}",),
                platform=target_platform,
            )

        if plat == "python":
            try:
                ast.parse(rendered)
            except SyntaxError as exc:
                return ExportResult(
                    success=False,
                    source_code="",
                    errors=(f"Generated Python code failed syntax validation: {exc}",),
                    platform=target_platform,
                )

        return ExportResult(
            success=True,
            source_code=rendered,
            errors=(),
            platform=target_platform,
        )


