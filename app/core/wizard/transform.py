SUPPORTED_PLATFORMS = frozenset({"mql5", "mql4", "easylanguage", "ctrader", "python"})
_SUPPORTED_COMPARATORS = frozenset({"==", "!=", ">", "<", ">=", "<="})
_MARKET_FIELDS = frozenset(
    {
        "open",
        "high",
        "low",
        "close",
        "volume",
        "tick_volume",
        "open_price",
        "high_price",
        "low_price",
        "close_price",
    }
)

_KNOWN_BLOCKS = frozenset(
    {"sma", "ema", "rsi", "atr", "bollinger", "macd", "stochastic", "price"}
)

_COMPARATOR_MAP_EL = {
    "==": "=",
    "!=": "<>",
    ">": ">",
    "<": "<",
    ">=": ">=",
    "<=": "<=",
}


@dataclass(frozen=True, slots=True)
class ExportResult:
    """Outcome of strategy code transformation and platform export."""

    success: bool
    source_code: str
    errors: tuple[str, ...]
    platform: str


@dataclass(frozen=True, slots=True)
class NormalizedParam:
    """Normalized user configurable parameter."""

    name: str
    type_name: str
    type_mql: str
    type_cs: str
    type_py: str
    value: Any


@dataclass(frozen=True, slots=True)
class NormalizedVar:
    """Normalized internal strategy state variable."""

    name: str
    type_name: str
    type_mql: str
    type_py: str
    value: Any


@dataclass(frozen=True, slots=True)
class NormalizedCondition:
    """Normalized condition expression with per-platform renderings."""

    expr_mql: str
    expr_el: str
    expr_cs: str
    expr_py: str


@dataclass(frozen=True, slots=True)
class NormalizedAction:
    """Normalized rule action with target parameters."""

    kind: str
    direction: int
    volume: float
    sl_pips: float
    tp_pips: float
    sl_expr_mql5: str
    tp_expr_mql5: str
    sl_expr_mql4: str
    tp_expr_mql4: str
    comment: str


@dataclass(frozen=True, slots=True)
class NormalizedRule:
    """Normalized trading rule containing conditions and actions."""

    name: str
    trigger: str
    conditions: tuple[NormalizedCondition, ...]
    actions: tuple[NormalizedAction, ...]
    is_enabled: bool
    cond_expr_mql: str = ""
    cond_expr_el: str = ""
    cond_expr_cs: str = ""
    cond_expr_py: str = ""


@dataclass(frozen=True, slots=True)
class NormalizedStrategy:
    """Intermediate Normalized AST representation of a strategy document."""

    strategy_id: str
    name: str
    class_name: str
    magic_number: int
    max_positions: int
    parameters: tuple[NormalizedParam, ...]
    variables: tuple[NormalizedVar, ...]
    rules: tuple[NormalizedRule, ...]


