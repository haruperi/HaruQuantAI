"""AI Assistant domain contracts, conversation turns, and completion models.

Description:
    Provides Pydantic data schemas for AI assistant chat conversations,
    multi-step turn executions, one-shot completions, memory configuration,
    and session persistence modeled after donor ServletSQAI contracts.

Purpose:
    FEAT-AI-ASSISTANT: Structured message, turn, completion, and session state
    for HaruQuantAI AI Assistant workspace.

Key Capabilities:
    - FR-ai-assistant-models: Strongly typed conversation messages, turn requests,
      execution steps, and completion records.

Python API Usage:
    from app.workspace.ai.assistant_models import ChatTurnRequest, ChatMessage

    req = ChatTurnRequest(message="What is the best EMA strategy?", session_id="s1")

CLI Usage:
    python -c "from app.workspace.ai.assistant_models import ChatTurnRequest; print(1)"
"""

from __future__ import annotations

import time
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class ChatMessage(BaseModel):
    """Single message entry in an AI assistant conversation history."""

    role: Literal["user", "assistant", "system"] = Field(
        ..., description="Message author role"
    )
    content: str = Field(..., description="Raw text or formatted markdown message")
    timestamp: float = Field(
        default_factory=time.time,
        description="Epoch timestamp when the message was posted",
    )
    attachments: list[str] = Field(
        default_factory=list,
        description="List of attached file names or safe document paths",
    )


class ChatStep(BaseModel):
    """Intermediate execution step within an agentic turn."""

    type: str = Field(
        default="thought",
        description="Step type: thought, tool_call, tool_result",
    )
    content: str = Field(..., description="Content or explanation of the step")
    tool_name: str | None = Field(
        default=None, description="Optional invoked tool name"
    )
    tool_args: dict[str, Any] | None = Field(
        default=None,
        description="Arguments passed to the tool",
    )


class ChatTurnRequest(BaseModel):
    """Request payload to initiate a conversation turn."""

    model_config = ConfigDict(populate_by_name=True)

    message: str = Field(..., description="User prompt or instructions")
    session_id: str | None = Field(
        default=None,
        alias="sessionId",
        description="Target session identifier",
    )
    async_: bool = Field(
        default=False,
        alias="async",
        description="Whether to run the turn asynchronously",
    )
    attachments: list[str] = Field(
        default_factory=list,
        description="List of attached file names or uploaded documents",
    )


class ChatTurnResponse(BaseModel):
    """Result payload from an executed conversation turn."""

    model_config = ConfigDict(populate_by_name=True)

    success: str = Field(
        ..., description="Final text answer or response from assistant"
    )
    history: list[ChatMessage] = Field(
        default_factory=list,
        description="Updated conversation history tail",
    )
    elapsed_ms: int = Field(
        default=0,
        alias="elapsedMs",
        description="Turn execution time in milliseconds",
    )
    tool_calls: int = Field(
        default=0,
        alias="toolCalls",
        description="Total number of tool calls executed",
    )
    stopped: bool = Field(
        default=False, description="Whether the turn was prematurely stopped"
    )
    steps: list[ChatStep] = Field(
        default_factory=list,
        description="Intermediate thought and tool steps",
    )
    actions: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Client-side UI action directives generated by the agent",
    )


class CompletionRequest(BaseModel):
    """Request payload for a direct, one-shot LLM completion."""

    prompt: str = Field(..., description="Input prompt for one-shot completion")
    system: str | None = Field(
        default=None,
        description="Optional system prompt overriding default assistant personality",
    )


class CompletionResponse(BaseModel):
    """Response payload containing one-shot completion output."""

    model_config = ConfigDict(populate_by_name=True)

    success: str = Field(..., description="Generated text completion")
    elapsed_ms: int = Field(
        default=0,
        alias="elapsedMs",
        description="Generation latency in milliseconds",
    )


class TurnStatus(BaseModel):
    """Current state of a running or completed conversation turn."""

    model_config = ConfigDict(populate_by_name=True)

    running: bool = Field(..., description="Whether a turn is actively processing")
    session_id: str | None = Field(
        default=None,
        alias="sessionId",
        description="Active session ID",
    )
    message: str = Field(default="", description="Active user prompt being processed")
    tool_calls: int = Field(
        default=0,
        alias="toolCalls",
        description="Tool invocations executed so far",
    )
    elapsed_ms: int = Field(
        default=0,
        alias="elapsedMs",
        description="Running duration in milliseconds",
    )
    stop_requested: bool = Field(
        default=False,
        alias="stopRequested",
        description="Whether cancellation was requested",
    )


class MemoryConfig(BaseModel):
    """Memory retention toggle and interval settings."""

    model_config = ConfigDict(populate_by_name=True)

    enabled: bool = Field(
        default=True, description="Whether AI conversation memory is active"
    )
    flush_interval_minutes: float = Field(
        default=0.0,
        alias="flushIntervalMinutes",
        description="Flush interval in minutes; 0 means after every turn",
    )


class SessionSummary(BaseModel):
    """Metadata summary of an AI assistant conversation session."""

    model_config = ConfigDict(populate_by_name=True)

    session_id: str = Field(
        ...,
        alias="sessionId",
        description="Unique session identifier",
    )
    name: str = Field(..., description="Session title or label")
    project: str = Field(default="", description="Associated workspace project name")
    message_count: int = Field(
        default=0,
        alias="messageCount",
        description="Total messages in the session",
    )
    pinned: bool = Field(
        default=False, description="Whether session is pinned to sidebar"
    )
    updated_at: float = Field(
        default_factory=time.time,
        alias="updatedAt",
        description="Last update timestamp",
    )


class ModelCatalog(BaseModel):
    """Available AI models and current selection status."""

    model_config = ConfigDict(populate_by_name=True)

    models: list[dict[str, Any]] = Field(
        default_factory=list,
        description="List of available LLM model descriptors",
    )
    default_model: str = Field(
        default="haru-quant-deepseek-v3",
        alias="defaultModel",
        description="Default model identifier",
    )
    current_model: str = Field(
        default="haru-quant-deepseek-v3",
        alias="currentModel",
        description="Currently active model identifier",
    )
    provider: str = Field(
        default="haru_internal",
        description="Active inference provider",
    )
    ready: bool = Field(
        default=True,
        description="Whether inference backend is ready to accept requests",
    )
