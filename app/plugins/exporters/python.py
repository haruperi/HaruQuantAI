"""Python code generator plugin consuming universal semantic IR.

Cohesive single-file plugin: the exporter's behavior, schema, bounds,
and presentation metadata live in this file. Stable identity:
``exporter.python@1.0.0``. The zero-argument ``plugin()`` factory is
pure and side-effect free — no I/O, no tasks or threads, no environment
reads, no registration — and the plugin is discovered through the host
catalog, never imported by name by the host or other plugins.

The exporter consumes a validated ``SemanticProgram`` (IR schema
version 1) and emits deterministic, formatted Python source plus an
immutable ``FrozenObject`` manifest carrying the target identity, IR
schema version, entry point, input/output keys, and the SHA-256 hash of
the generated source. It knows only the universal ``std.*``
primitives: any unknown operator or unsupported recurrence method is
rejected with a ValueError naming the offending primitive. It has no
knowledge of RSI or any other concrete plugin. Executing the generated
code is a test-only concern.
"""

