def approval_refusal(
    principal: ApprovingPrincipal | None,
    environment: str,
) -> str | None:
    """Report why one principal may not approve a promotion.

    Args:
        principal: Candidate approving principal, or None when absent.
        environment: Environment the promotion targets.

    Returns:
        A refusal message, or None when the principal may approve.
    """
    if principal is None:
        return "promotion requires an authenticated human approval"
    if principal.principal_type != "USER":
        return (
            "promotion approval requires a human principal; "
            f"{principal.principal_type!r} cannot approve"
        )
    if PROMOTION_PERMISSION not in principal.permissions:
        return f"the approving principal does not hold {PROMOTION_PERMISSION}"
    if principal.tenant_or_environment != environment:
        return (
            f"the approval was issued for {principal.tenant_or_environment!r}, "
            f"not for {environment!r}"
        )
    return None


class _StateHolder(Protocol):
    """Minimal structural view of something carrying a recorded state."""

    state: ArtifactState


def latest_state(records: tuple[_StateHolder, ...]) -> ArtifactState | None:
    """Return the current state implied by an ordered history.

    Args:
        records: Ordered lifecycle history, oldest first.

    Returns:
        The most recent state, or None when there is no history.
    """
    if not records:
        return None
    return records[-1].state
