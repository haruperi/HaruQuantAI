"""Promotion evidence packets, lifecycle records, and the transition machine.

`PromotionEvidencePacket` makes the ordered evidence complete
(`FR-AGENTIC-052`): every required piece is its own non-defaulted field, so a
packet assembled without a critique, without a sweep, or without an approving
principal is not a weaker packet but an unconstructable one. The packet carries
a digest over the whole assembly, so evidence appended after approval yields a
different packet.

`LifecycleRecord` makes transitions append-only and version-specific
(`FR-AGENTIC-054`). Records are keyed on the **artefact digest**, not the
artefact identity: change one generated byte and the digest changes, so the
altered artefact begins at `staged` with no history to inherit. `_PREDECESSORS`
states which state may follow which, so a skipped step is unrepresentable and
demotion from `registered` is always available.

`research_only` is terminal (`FR-AGENTIC-053`). Nothing leaves it. An artefact
that leaked, reused holdout, exhausted its search budget, arrived without
provenance, or was never approved does not get a second run at the gate under a
freshly assembled packet.
"""

